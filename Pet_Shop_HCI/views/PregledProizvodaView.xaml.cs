        private void DataGrid_AutoGeneratedColumns(object sender, EventArgs e)
        {
            foreach (var column in ProizvodiDataGrid.Columns)
            {
                if (column.Header == null)
                {
                    column.Width = 80;
                }
                else if (column.Header.ToString() == "Naziv")
                {
                    column.Width = 115;
                }
                else if (column.Header.ToString() == "Šifra")
                {
                    column.Width = 90;
                }
                else if (column.Header.ToString() == "Stanje")
                {
                    column.Width = 60;
                }
                else if (column.Header.ToString() == "Cijena (KM)")
                {
                    column.Width = 85;
                }
                else if (column.Header.ToString() == "Vrsta životinje")
                {
                    column.Width = 100;
                }
                else if (column.Header.ToString() == "Težina (kg)")
                {
                    column.Width = 80;
                }
                else if (column.Header.ToString() == "Uzrast (m)")
                {
                    column.Width = 75;
                }
                else if (column.Header.ToString() == "Vrsta")
                {
                    column.Width = 70;
                }
                else if (column.Header.ToString() == "Rasa")
                {
                    column.Width = 70;
                }
                else
                {
                    column.Width = new DataGridLength(1, DataGridLengthUnitType.Star);
                }
            }
        }

