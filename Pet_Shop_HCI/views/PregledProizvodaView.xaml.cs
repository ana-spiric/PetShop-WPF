            this.DataContext = pregledProizvoda;
        }

        private void SearchTextBox_GotFocus(object sender, RoutedEventArgs e)
        {
            TextBox textBox = sender as TextBox;
            if (textBox != null)
            {
                string currentText = textBox.Text;
                PregledProizvoda pregled = DataContext as PregledProizvoda;
                if (pregled != null)
                {
                    pregled.SearchText = currentText;
                }
            }
        }

        private void SearchTextBox_TextChanged(object sender, TextChangedEventArgs e)
        {
            if (DataContext is PregledProizvoda pregled)
            {
                pregled.SearchText = SearchTextBox.Text;
            }
        }

        private void Asesoar_Click(object sender, RoutedEventArgs e)
        {
            tip = "Asesoar";
            pregledProizvoda.TipProizvoda = "Asesoar";
            pregledProizvoda.loadAsesoar();
        }

        private void SviProizvodi_Click(object sender, RoutedEventArgs e)
        {
            tip = "Svi";
            pregledProizvoda.TipProizvoda = "Svi";
            pregledProizvoda.loadSviProizvodi();
        }

        private void Ljubimci_Click(object sender, RoutedEventArgs e)
        {
            tip = "Ljubimci";
            pregledProizvoda.TipProizvoda = "Ljubimci";
            pregledProizvoda.loadLjubimci();
        }

