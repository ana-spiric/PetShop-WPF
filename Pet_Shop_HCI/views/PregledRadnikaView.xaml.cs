namespace Pet_Shop_HCI.views
{
    /// <summary>
    /// Interaction logic for PregledRadnikaView.xaml
    /// </summary>
    public partial class PregledRadnikaView : UserControl
    {
        private PregledRadnika pregledRadnika;
        public PregledRadnikaView()
        {
            InitializeComponent();
            pregledRadnika = new PregledRadnika();
            this.DataContext = pregledRadnika;
        }

        private void SearchTextBox_GotFocus(object sender, RoutedEventArgs e)
        {
            TextBox textBox = sender as TextBox;
            if (textBox != null)
            {
                string currentText = textBox.Text;
                PregledRadnika pregled = DataContext as PregledRadnika;
                if (pregled != null)
                {
                    pregled.SearchText = currentText;
                }
            }
        }

        private void SearchTextBox_TextChanged(object sender, TextChangedEventArgs e)
        {
            if (DataContext is PregledRadnika pregled)
            {
                pregled.SearchText = SearchTextBox.Text;
            }
        }

        private void DodajRadnikaButton_Click(object sender, RoutedEventArgs e)
        {
            DodajRadnikaWindow dodajRadnika = new DodajRadnikaWindow();
            dodajRadnika.ShowDialog();
            pregledRadnika = new PregledRadnika();
            this.DataContext = pregledRadnika;
        }

        private void DataGrid_AutoGeneratedColumns(object sender, EventArgs e)
        {
            foreach (var column in RadniciDataGrid.Columns)
            {
                if (column.Header == null)
                {
                    column.Width = 80;
                }
                else if (column.Header.ToString() == "Status")
                {
                    column.Width = 60;
                }
                else if (column.Header.ToString() == "Admin")
                {
                    column.Width = 60;
                }
                else
                {
                    column.Width = new DataGridLength(1, DataGridLengthUnitType.Star);
                }
            }
        }
    }
}
