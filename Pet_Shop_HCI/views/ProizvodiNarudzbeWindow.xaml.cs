    public partial class ProizvodiNarudzbeWindow : Window
    {
        public ProizvodiNarudzbeWindow(string sifra, string datum, string ime, string prezime, string naziv, string cijena)
        {
            InitializeComponent();
            ProizvodiNabavka proizvodi = new ProizvodiNabavka(sifra, cijena)
            {
                Podaci = ConPodaci(sifra, datum, ime, prezime, naziv)
            };
            DataContext = proizvodi;
        }

        private string ConPodaci(string sifra, string datum, string ime, string prezime, string naziv)
        {
            return $"Narudžbu ({sifra}) kreirao/la {ime} {prezime} ({datum}) - {naziv}";
        }
        private void btnClose_Click(object sender, RoutedEventArgs e)
        {
            this.Close();
        }

        private void SearchTextBox_GotFocus(object sender, RoutedEventArgs e)
        {
            TextBox textBox = sender as TextBox;
            if (textBox != null)
            {
                string currentText = textBox.Text;
                ProizvodiNabavka pregled = DataContext as ProizvodiNabavka;
                if (pregled != null)
                {
                    pregled.SearchTextNabavka = currentText;
                }
            }
        }

        private void SearchTextBox_TextChanged(object sender, TextChangedEventArgs e)
        {
            if (DataContext is ProizvodiNabavka pregled)
            {
                pregled.SearchTextNabavka = SearchTextBox.Text;
            }
        }

        private void DataGrid_AutoGeneratedColumnsN(object sender, EventArgs e)
        {
            foreach (var column in NProizvodiGrid.Columns)
            {
                if (column.Header.ToString() == "Šifra")
                {
                    column.Width = 100;
                }
                if (column.Header.ToString() == "Naziv")
                {
                    column.Width = 140;
                }
                else if (column.Header.ToString() == "Količina")
                {
                    column.Width = 100;
                }
                else
                {
                    column.Width = new DataGridLength(1, DataGridLengthUnitType.Star);
                }
            }
        }
    }
}
