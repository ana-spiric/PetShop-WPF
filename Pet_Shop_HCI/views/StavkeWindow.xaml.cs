namespace Pet_Shop_HCI.views
{
    /// <summary>
    /// Interaction logic for StavkeWindow.xaml
    /// </summary>
    public partial class StavkeWindow : Window
    {
        public StavkeWindow(string sifra, string datum, string ime, string prezime, string cijena)
        {
            InitializeComponent();
            StavkeRacuna stavke = new StavkeRacuna(sifra, cijena)
            {
                Podaci = ConPodaci(sifra, datum, ime, prezime)
            };
            DataContext = stavke;
        }

        private string ConPodaci(string sifra, string datum, string ime, string prezime)
        {
            return $"Račun ({sifra}) kreirao/la {ime} {prezime} ({datum})";
        }
        private void btnClose_Click(object sender, RoutedEventArgs e)
        {
            this.Close();
        }

        private void SearchTextBox_GotFocus(object sender, RoutedEventArgs e)
        {
            TextBox textBox = sender as TextBox;
            if (textBox != null)
            {
                string currentText = textBox.Text;
                StavkeRacuna pregled = DataContext as StavkeRacuna;
                if (pregled != null)
                {
                    pregled.SearchTextRacun = currentText;
                }
            }
        }

        private void SearchTextBox_TextChanged(object sender, TextChangedEventArgs e)
        {
            if (DataContext is ProizvodiNabavka pregled)
            {
                pregled.SearchTextNabavka = SearchTextBox.Text;
            }
        }

        private void DataGrid_AutoGeneratedColumnsN(object sender, EventArgs e)
        {
            foreach (var column in StavkeGrid.Columns)
            {
                if (column.Header.ToString() == "Šifra")
                {
                    column.Width = 100;
                }
                if (column.Header.ToString() == "Naziv")
                {
                    column.Width = 140;
                }
                else if (column.Header.ToString() == "Količina")
                {
                    column.Width = 100;
                }
                else
                {
                    column.Width = new DataGridLength(1, DataGridLengthUnitType.Star);
                }
            }
        }
    }
}
