    /// <summary>
    /// Interaction logic for PregledNarudzbiView.xaml
    /// </summary>
    public partial class PregledNarudzbiView : UserControl
    {
        private PregledNarudzbi pregled;
        public PregledNarudzbiView()
        {
            InitializeComponent();
            pregled = new PregledNarudzbi();
            this.DataContext = pregled;
        }

        private void SearchTextBox_GotFocus(object sender, RoutedEventArgs e)
        {
            TextBox textBox = sender as TextBox;
            if (textBox != null)
            {
                string currentText = textBox.Text;
                PregledProizvoda pregled = DataContext as PregledProizvoda;
                if (pregled != null)
                {
                    pregled.SearchText = currentText;
                }
            }
        }

        private void SearchTextBox_TextChanged(object sender, TextChangedEventArgs e)
        {
            if (DataContext is PregledProizvoda pregled)
            {
                pregled.SearchText = SearchTextBox.Text;
            }
        }

        private void DataGrid_AutoGeneratedColumns(object sender, EventArgs e)
        {
            foreach (var column in NarudzbeDataGrid.Columns)
            {
                if (column.Header == null)
                {
                    column.Width = 80;
                }
                else if(column.Header.ToString() == "Šifra narudžbe")
                {
                    column.Width = 110;
                }
                else if (column.Header.ToString() == "Ukupna cijena")
                {
                    column.Width = 100;
                } 
                else if (column.Header.ToString() == "Datum kreiranja")
                {
                    column.Width = 160;
                }
                else
                {
                    column.Width = new DataGridLength(1, DataGridLengthUnitType.Star);
                }
            }
        }

    }
}
